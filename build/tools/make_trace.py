"""docs/TRACEABILITY.md = PLAN.md features x automated tests (from test --trace output) x FAT steps (docs/FAT.md)."""
import re, sys, os, collections
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
trace_file = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "artifacts", "trace.md")
plan = open(os.path.join(root, "PLAN.md"), encoding="utf-8").read()
features = re.findall(r"^- ((?:USR|REC|BAT|CAM|PLC|ALM|AUD|RPT|SYS)-\d+) (.+)$", plan, re.M)
tests = collections.defaultdict(list)
for line in open(trace_file, encoding="utf-8"):
    m = re.match(r"\| ([A-Z]{3}-\d+(?:, [A-Z]{3}-\d+)*) \| (\S+) \| (\w+) \|", line)
    if m:
        for fid in m.group(1).split(", "):
            tests[fid].append(f"{m.group(2)} ({m.group(3)})")
fat = open(os.path.join(root, "docs", "FAT.md"), encoding="utf-8").read()
fat_steps = collections.defaultdict(list)
for m in re.finditer(r"^\| (FAT-\d+) \| ([^|]+) \|", fat, re.M):
    for fid in re.findall(r"[A-Z]{3}-\d+", m.group(2)):
        fat_steps[fid].append(m.group(1))
out = ["# Requirement traceability", "",
       "Generated by `build/tools/make_trace.py` from PLAN.md, the automated test run (`--trace`) and docs/FAT.md.", "",
       "| ID | Requirement | Automated tests | FAT step |", "|---|---|---|---|"]
missing = []
for fid, text in features:
    t = "<br>".join(tests.get(fid, [])) or "—"
    f = ", ".join(fat_steps.get(fid, [])) or "—"
    if t == "—" and f == "—": missing.append(fid)
    out.append(f"| {fid} | {text.replace('|','/')} | {t} | {f} |")
out += ["", f"Features: {len(features)}; with automated test: {sum(1 for f,_ in features if tests.get(f))}; uncovered: {', '.join(missing) or 'none'}."]
open(os.path.join(root, "docs", "TRACEABILITY.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(out[-1])
sys.exit(1 if missing else 0)
